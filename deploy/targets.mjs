// Per-host extras for one build (M16 Part D). Reads the built site and writes:
//   <public>/build.txt        commit stamp, served by every host (smoke tests read it)
//   <out>/cloudflare/         site + `_headers` (Cloudflare Pages)
//   <out>/apache/             site + `.htaccess` (shared hosting: Apache / LiteSpeed, e.g. Hostinger)
// GitHub Pages serves <public> as is (it cannot set headers); the container image gets the same
// headers from nginx (security-headers.conf + csp.mjs). All of them come from headers.mjs.
// Usage: node deploy/targets.mjs <public dir> <out dir> <commit sha>
import { cp, mkdir, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { SECURITY_HEADERS, buildCsp } from "./headers.mjs"

/** Cloudflare Pages drops `_headers` values longer than this. */
export const CLOUDFLARE_MAX = 2000

/** Cloudflare Pages `_headers`: rules per URL pattern, each header on its own indented line. */
export function cloudflareHeaders(policy) {
  const all = [["Content-Security-Policy", policy], ...SECURITY_HEADERS]
  return [
    "# Generated by deploy/targets.mjs from deploy/headers.mjs. Do not edit.",
    "/*",
    ...all.map(([k, v]) => `  ${k}: ${v}`),
    "  Cache-Control: no-cache",
    "/static/*",
    "  Cache-Control: public, max-age=3600",
    "/*.css",
    "  Cache-Control: public, max-age=3600",
    "/*.js",
    "  Cache-Control: public, max-age=3600",
    "",
  ].join("\n")
}

/** Apache / LiteSpeed `.htaccess`: headers, clean URLs (Quartz links pages without .html), 404. */
export function htaccess(policy) {
  const quote = (v) => `"${v.replace(/"/g, '\\"')}"`
  const all = [["Content-Security-Policy", policy], ...SECURITY_HEADERS]
  return [
    "# Generated by deploy/targets.mjs from deploy/headers.mjs. Do not edit.",
    "Options -Indexes -MultiViews",
    "DirectoryIndex index.html",
    "ErrorDocument 404 /404.html",
    "",
    "<IfModule mod_headers.c>",
    ...all.map(([k, v]) => `  Header always set ${k} ${quote(v)}`),
    "  Header always unset X-Powered-By",
    '  Header set Cache-Control "no-cache"',
    '  <FilesMatch "\\.(css|js|json|png|jpe?g|gif|webp|avif|svg|ico|woff2?)$">',
    '    Header set Cache-Control "public, max-age=3600"',
    "  </FilesMatch>",
    "</IfModule>",
    "",
    "<IfModule mod_rewrite.c>",
    "  RewriteEngine On",
    "  # HTTPS only",
    "  RewriteCond %{HTTPS} !=on",
    "  RewriteCond %{HTTP:X-Forwarded-Proto} !=https",
    "  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]",
    "  # no dotfiles except .well-known",
    "  RewriteRule (^|/)\\.(?!well-known/) - [F]",
    "  # /page -> page.html",
    "  RewriteCond %{REQUEST_FILENAME} !-f",
    "  RewriteCond %{REQUEST_FILENAME} !-d",
    "  RewriteCond %{REQUEST_FILENAME}.html -f",
    "  RewriteRule ^(.+?)/?$ $1.html [L]",
    "</IfModule>",
    "",
  ].join("\n")
}

async function main() {
  const [publicDir, outDir, sha] = process.argv.slice(2)
  if (!publicDir || !outDir || !sha) {
    console.error("usage: node deploy/targets.mjs <public dir> <out dir> <commit sha>")
    process.exit(1)
  }
  await writeFile(path.join(publicDir, "build.txt"), `${sha}\n`)
  const { policy, scripts, styles } = await buildCsp(publicDir)
  if (/unsafe-inline|unsafe-eval/.test(policy)) throw new Error("CSP must stay strict")
  if (policy.length > CLOUDFLARE_MAX)
    console.warn(
      `warning: CSP is ${policy.length} chars; Cloudflare Pages ignores header values over ${CLOUDFLARE_MAX}`,
    )
  const targets = {
    cloudflare: ["_headers", cloudflareHeaders(policy)],
    apache: [".htaccess", htaccess(policy)],
  }
  for (const [name, [file, text]] of Object.entries(targets)) {
    const dir = path.join(outDir, name)
    await rm(dir, { recursive: true, force: true })
    await mkdir(dir, { recursive: true })
    await cp(publicDir, dir, { recursive: true })
    await writeFile(path.join(dir, file), text)
  }
  console.log(
    `targets: ${Object.keys(targets).join(", ")} (CSP ${policy.length} chars: ${scripts} script, ${styles} style hash(es)), build ${sha}`,
  )
}

if (import.meta.url === `file://${process.argv[1]}`) await main()
